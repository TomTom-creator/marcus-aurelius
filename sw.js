function getDailyQuote() {
  var day = Math.floor(Date.now() / 86400000);
  return QUOTES[day % QUOTES.length];
}

self.addEventListener('install', function(e) {
  self.skipWaiting();
});

self.addEventListener('activate', function(e) {
  e.waitUntil(self.clients.claim());
});

self.addEventListener('notificationclick', function(e) {
  e.notification.close();
  e.waitUntil(
    self.clients.matchAll({type:'window'}).then(function(clients) {
      if (clients.length > 0) return clients[0].focus();
      return self.clients.openWindow('/');
    })
  );
});

// Receive alarm time from main page and set up interval check
self.addEventListener('message', function(e) {
  if (e.data && e.data.type === 'SET_ALARM') {
    self.alarmHour = e.data.hour;
    self.alarmMinute = e.data.minute;
    self.alarmEnabled = e.data.enabled;
  }
});

// Use a recurring sync check via the client — the SW stays alive
// The main mechanism: when the app sends a CHECK message every minute
self.addEventListener('message', function(e) {
  if (e.data && e.data.type === 'CHECK_ALARM') {
    if (!self.alarmEnabled) return;
    var now = new Date();
    if (now.getHours() === self.alarmHour && now.getMinutes() === self.alarmMinute) {
      self.registration.showNotification('Marcus Aurelius – Meditationen', {
        body: getDailyQuote(),
        icon: 'https://upload.wikimedia.org/wikipedia/commons/thumb/e/ec/Mona_Lisa%2C_by_Leonardo_da_Vinci%2C_from_C2RMF_retouched.jpg/1024px-Mona_Lisa%2C_by_Leonardo_da_Vinci%2C_from_C2RMF_retouched.jpg',
        badge: '',
        vibrate: [200, 100, 200],
        tag: 'daily-quote',
        renotify: false
      });
    }
  }
});
